class CalcClass :
    def add(self, num1, num2):
        res = num1 + num2
        return res

    def sub(self, num1, num2):
        res = num1 - num2
        return res

    def mul(self, num1, num2):
        res = num1 * num2
        return res

    def div(self, num1, num2):
        res = num1 / num2
        return res

